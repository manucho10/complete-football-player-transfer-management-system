// src/lib/generateContract.js
import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';

export const generateTransferContract = (offer) => {
    // 1. Initialize the document
    const doc = new jsPDF();

    // 2. Set up the fonts and colors
    const primaryColor = '#10b981'; // Tailwind green-500
    const darkColor = '#111827';    // Tailwind gray-900

    // --- HEADER ---
    doc.setFillColor(darkColor);
    doc.rect(0, 0, 210, 40, 'F'); // Dark header background

    doc.setTextColor(255, 255, 255);
    doc.setFontSize(24);
    doc.setFont('helvetica', 'bold');
    doc.text('TRANSFER AGREEMENT', 14, 25);

    doc.setFontSize(10);
    doc.setFont('helvetica', 'normal');
    doc.text(`Date: ${new Date().toLocaleDateString()}`, 14, 32);
    doc.text(`Contract Ref: TRF-${offer.id.substring(0, 8).toUpperCase()}`, 150, 32);

    // --- BODY ---
    doc.setTextColor(darkColor);
    doc.setFontSize(12);
    doc.setFont('helvetica', 'bold');
    doc.text('1. PARTIES INVOLVED', 14, 55);

    doc.setFontSize(10);
    doc.setFont('helvetica', 'normal');
    doc.text(`Buying Club: ${offer.from_name || 'Not specified'}`, 14, 63);
    doc.text(`Selling Club: ${offer.to_name || 'Not specified'}`, 14, 70);
    doc.text(`Player Name: ${offer.playerName || 'Not specified'}`, 14, 77);
    doc.text(`Position: ${offer.player_position || 'N/A'}`, 14, 84);

    // --- TERMS TABLE ---
    doc.setFontSize(12);
    doc.setFont('helvetica', 'bold');
    doc.text('2. TRANSFER TERMS', 14, 100);

    autoTable(doc, {
        startY: 105,
        head: [['Description', 'Details']],
        body: [
            ['Transfer Fee', `€${Number(offer.amount).toLocaleString()}`],
            ['Contract Duration', offer.duration || 'N/A'],
            ['Annual Salary', offer.salary || 'N/A'],
            ['Status', 'ACCEPTED'],
        ],
        theme: 'grid',
        headStyles: { fillColor: primaryColor, textColor: 255 },
        styles: { fontSize: 10, cellPadding: 4 },
    });

    // --- SIGNATURES ---
    const finalY = doc.lastAutoTable.finalY + 30;

    doc.setFontSize(10);
    doc.text('_____________________________', 20, finalY);
    doc.text('Authorized Signature (Buying Club)', 20, finalY + 7);

    doc.text('_____________________________', 130, finalY);
    doc.text('Authorized Signature (Selling Club)', 130, finalY + 7);

    // --- FOOTER ---
    doc.setFontSize(8);
    doc.setTextColor(150);
    doc.text('This document was automatically generated by TransferHub. No signature is legally binding without physical authorization.', 105, 285, { align: 'center' });

    // 3. Save the PDF
    doc.save(`Transfer_Contract_${offer.playerName?.replace(/\s+/g, '_') || 'Draft'}.pdf`);
};